-- Development reset: this intentionally deletes all existing auth users and sessions.
DROP TABLE IF EXISTS refresh_tokens;
DROP TABLE IF EXISTS oauth_identities;
DROP TABLE IF EXISTS password_credentials;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE password_credentials (
    user_id BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE oauth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider VARCHAR(50) NOT NULL,
    provider_subject VARCHAR(255) NOT NULL,
    provider_email VARCHAR(255) NOT NULL,
    CONSTRAINT ux_oauth_provider_subject UNIQUE (provider, provider_subject),
    CONSTRAINT ux_oauth_user_provider UNIQUE (user_id, provider)
);

CREATE TABLE refresh_tokens (
    token_id VARCHAR(255) PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    session_id VARCHAR(36),
    device_name VARCHAR(100)
);

CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_session_id ON refresh_tokens (session_id);
